# Write src/data/roomLamps.js: every real light a player sees glow in each room (lamp shades, sconces, lanterns,
# the service corridor's strip light), as the room and lobby pipelines build them, for the game's lamp halos
# (src/render/lampHalos.js). One record per light: the model object it belongs to, the middle of its glowing part,
# that part's size, its watts and its colour (LAMPS in roomkit.py, make_room.py and make_lobby.py).
#
#   python3 tools/room-pipeline/export_lamps.py                 every room tile and the lobby (~5 s each)
#   python3 tools/room-pipeline/export_lamps.py lounge hall     only these (the others keep their records)
#
# It runs make_room.py / make_lobby.py with --lamps, which stop before the bake and the export: the shipped models
# and light maps are untouched. Run it after a room's decoration changes (build_all.sh runs it at the end).
import json, os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
OUT = os.path.join(REPO, 'src', 'data', 'roomLamps.js')

rooms = list(json.load(open(os.path.join(HERE, 'rooms.json')))['rooms'])
wanted = sys.argv[1:] or ['hall'] + rooms

# the records already written (a partial run keeps the rooms it does not rebuild)
known = {}
if os.path.exists(OUT):
    m = re.search(r'export const ROOM_LAMPS = (\{.*\});', open(OUT).read(), re.S)
    if m:
        known = json.loads(m.group(1))

with tempfile.TemporaryDirectory() as tmp:
    for room in wanted:
        path = os.path.join(tmp, room + '.json')
        if room == 'hall':
            cmd = [sys.executable, os.path.join(REPO, 'tools', 'lobby-pipeline', 'make_lobby.py'), '--lamps', path]
        elif room in rooms:
            cmd = [sys.executable, os.path.join(HERE, 'make_room.py'), '--room', room, '--lamps', path]
        else:
            sys.exit('no such room: %s' % room)
        run = subprocess.run(cmd, capture_output=True, text=True)
        if run.returncode != 0 or not os.path.exists(path):
            sys.exit('%s failed:\n%s' % (room, (run.stdout + run.stderr)[-2000:]))
        known[room] = [{'kind': l['kind'], 'node': l['node'], 'at': l['at'], 'ext': l['ext'], 'watts': l['watts'], 'color': l['color']}
                       for l in json.load(open(path))['lamps']]
        print('%-16s %2d lamps' % (room, len(known[room])))

order = ['hall'] + [r for r in rooms if r in known]
lines = ['// GENERATED by tools/room-pipeline/export_lamps.py from the room and lobby pipelines: do not edit by hand (re-run it).',
         '// Every real light a player sees glow in each room (lamp shades, sconces, lanterns, the service corridor\'s strip',
         '// light), for the lamp halos (src/render/lampHalos.js). Per light: `kind`; `node`, the model object it belongs to',
         '// (a wall\'s upper part folds down in the cutaway and its halo goes with it); `at`, the middle of its glowing part',
         '// in the model\'s own space (metres, the tile in its default orientation); `ext`, that part\'s largest size (m);',
         '// `watts` and `color` (linear RGB), as baked.',
         'export const ROOM_LAMPS = {']
for room in order:
    rows = ',\n'.join('    ' + json.dumps(l, separators=(', ', ': ')) for l in known[room])
    lines.append('  %s: [\n%s,\n  ],' % (json.dumps(room), rows) if rows else '  %s: [],' % json.dumps(room))
lines.append('};')
text = '\n'.join(lines) + '\n'
# (the JSON object between the braces must stay parseable for a partial re-run: quoted keys, no trailing commas)
text = text.replace(',\n  ],', '\n  ],').replace('],\n};', ']\n};')
open(OUT, 'w').write(text)
print('wrote', os.path.relpath(OUT, REPO), sum(len(v) for v in known.values()), 'lamps in', len(order), 'rooms')
